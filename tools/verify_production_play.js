// Actual UI controls, authoritative server clock, both production screens. No engine fast-forward.
async (page) => {
  const origin = new URL(page.url()).origin;
  const out = '/Users/teresapeng/Documents/Codex/2026-11-19/bang/outputs/moonfall-playable-release';
  const errors=[],requests=[],checks=[],timeline=[];
  const watch=p=>{p.on('pageerror',e=>errors.push(e.message));p.on('response',r=>{if(r.status()>=400)requests.push([r.status(),r.url()]);});};
  watch(page);
  let floor=page.context().pages().find(p=>new URL(p.url()).pathname==='/floor.html')||await page.context().newPage();watch(floor);
  const check=(name,ok,details)=>{checks.push({name,ok,details});if(!ok)throw Error(name+' '+JSON.stringify(details));};
  const state=()=>page.evaluate(()=>moonfallSandbox.snapshot());
  const wait=(fn,timeout=140000)=>page.waitForFunction(fn,null,{timeout});
  await page.setViewportSize({width:3456,height:1944});
  await page.goto(origin+'/sandbox.html?admin=1');
  await wait(()=>moonfallSandbox.controller()&&moonfallSandbox.world()?.ready);
  await floor.setViewportSize({width:1920,height:1080});
  await floor.goto(origin+'/floor.html');
  await floor.waitForFunction(()=>moonfallFloor.snapshot()&&moonfallFloor.world().ready);
  if((await state()).status!=='idle'){await page.locator('#reset').click();await wait(()=>moonfallSandbox.snapshot().status==='idle');}
  await page.locator('#speed').selectOption('1');
  await page.locator('#aftershock').selectOption('stable');
  await page.locator('#configure').click();
  await page.locator('[data-choice="outer"][data-robot="rover-blue"]').click();
  await page.locator('[data-choice="beacon"][data-robot="rover-gold"]').click();
  await page.locator('#start').click();
  await wait(()=>moonfallSandbox.snapshot().status==='running');
  const match=(await state()).match_id;
  await wait(()=>moonfallSandbox.snapshot().robots.every(r=>r.s_cm>5));
  const capture=async name=>{
    const a=await state(),b=await floor.evaluate(()=>moonfallFloor.snapshot());
    timeline.push({name,control:a,floor:b});
    check(name+' same match',a.match_id===b.match_id);
    check(name+' synchronized clock',Math.abs(a.elapsed_ms-b.elapsed_ms)<700);
    check(name+' synchronized stage/routes',a.robots.every((r,i)=>r.stage_id===b.robots[i].stage_id&&r.route_key===b.robots[i].route_key));
    check(name+' synchronized poses',a.robots.every((r,i)=>Math.hypot(r.pose.x_cm-b.robots[i].pose.x_cm,r.pose.y_cm-b.robots[i].pose.y_cm)<2));
    check(name+' same events/result',a.aftershock===b.aftershock&&a.winner===b.winner);
    return a;
  };
  await capture('moving');
  const prior=(await state()).elapsed_ms;
  await floor.reload();await floor.waitForFunction(()=>moonfallFloor.world().ready&&moonfallFloor.snapshot()?.elapsed_ms>0);
  await capture('floor refresh while moving');
  check('floor refresh does not reset or pause match',(await state()).status==='running'&&(await state()).elapsed_ms>prior);
  await floor.close();
  floor=await page.context().newPage();watch(floor);await floor.setViewportSize({width:1920,height:1080});
  await floor.goto(origin+'/floor.html');await floor.waitForFunction(()=>moonfallFloor.world().ready&&moonfallFloor.snapshot());
  await capture('reopened floor');
  check('reopened floor stays read-only',!(await floor.evaluate(()=>moonfallSandbox.controller())));
  await page.locator('#pause').click();await wait(()=>moonfallSandbox.snapshot().status==='paused');
  await page.waitForTimeout(200);const paused=await state();
  await page.waitForTimeout(900);const still=await capture('paused');
  check('pause freezes clock and both poses',still.elapsed_ms===paused.elapsed_ms&&JSON.stringify(still.robots.map(r=>r.pose))===JSON.stringify(paused.robots.map(r=>r.pose)));
  const geometryCheck=await page.evaluate(async()=>{
    const {toView}=await import('./display/map.js');const {mapPoint}=await import('./ruins-map.js');
    const s=moonfallSandbox.snapshot(),v=toView(s),w=moonfallSandbox.world();
    return v.players.map((p,i)=>{const q=mapPoint([p.position.x,p.position.y],i),a=w.roverPositions[i];return Math.hypot(q.x-a[0],q.y-a[1],q.z-a[2]);});
  });
  check('rendered rovers use unchanged authoritative mapping',geometryCheck.every(v=>v<1e-5),geometryCheck);
  await page.locator('#query').click();await wait(()=>moonfallSandbox.snapshot().snapshot_ok);
  await page.locator('#resume').click();await wait(()=>moonfallSandbox.snapshot().status==='running');
  await wait(()=>moonfallSandbox.snapshot().quake_ms!==null);
  const quake=await state();
  await page.locator('[data-choice="risk"][data-robot="rover-blue"]').click();
  check('one choice remains secret',(await state()).robots.every(r=>r.final===null));
  await wait(()=>moonfallSandbox.snapshot().locked);
  const lock=await state();
  check('seven-second timeout defaults unsubmitted player to safe',lock.robots[0].final==='risk'&&lock.robots[1].final==='safe'&&lock.elapsed_ms-lock.quake_ms>=7000, {quake:lock.quake_ms,locked:lock.elapsed_ms});
  check('cars keep moving during choice window',lock.robots.every((r,i)=>r.stage_id>quake.robots[i].stage_id||r.s_cm>quake.robots[i].s_cm+5));
  await capture('choice lock');
  await page.locator('[data-view="overview"]').click();
  await page.screenshot({path:out+'/panorama-3.5k.png'});
  await floor.locator('#floor-map').screenshot({path:out+'/floor-mid-match.png'});
  await wait(()=>moonfallSandbox.snapshot().status==='finished');
  const done=await capture('finish');
  check('real-time match finishes and both cars park',done.speed===1&&done.match_id===match&&!!done.winner&&done.robots.every(r=>r.parked&&r.finished_ms!==null));
  check('gold beacon opens door and closes after full passage',done.robots[1].beacon&&!done.robots[1].gate&&done.events.some(e=>e.type==='beacon'&&e.text.includes('rover-gold'))&&done.events.some(e=>e.type==='gate'&&e.text.includes('rover-gold')));
  check('stable outcome shared by both screens',done.aftershock==='stable');
  check('result is visible in console',(await page.locator('#notice').innerText()).includes('抵达'));
  check('floor renderer exposes same finished result',(await floor.evaluate(()=>moonfallFloor.world())).winner===done.winner);
  await page.screenshot({path:out+'/result-3.5k.png'});await floor.locator('#floor-map').screenshot({path:out+'/floor-finish.png'});
  await page.waitForTimeout(3500);
  const performance={computer:await page.evaluate(()=>moonfallSandbox.world()),floor:await floor.evaluate(()=>moonfallFloor.world())};
  check('same production art revision on both screens',performance.computer.artRevision===performance.floor.artRevision&&performance.computer.artRevision==='moonfall-unified-2026-11-24');
  check('3.5K view keeps adaptive GPU budget',performance.computer.renderSize[0]*performance.computer.renderSize[1]<=1800000,performance.computer.renderSize);
  check('full scene stays interactive at 3.5K viewport',performance.computer.medianFps>=30,performance.computer.medianFps);
  const sizes=await page.locator('#start').evaluate(el=>({font:parseFloat(getComputedStyle(el).fontSize),width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height}));
  check('control text and buttons remain legible',sizes.font>=12&&sizes.height>=32,sizes);
  await floor.setViewportSize({width:3840,height:2160});await floor.waitForTimeout(2500);
  const floor4k=await floor.evaluate(()=>moonfallFloor.world());check('4K floor remains responsive',floor4k.fps>=30,floor4k.fps);
  await floor.locator('#floor-map').screenshot({path:out+'/floor-finish-4k.png'});
  await page.locator('#reset').click();await wait(()=>moonfallSandbox.snapshot().status==='idle');
  await floor.waitForFunction(()=>moonfallFloor.snapshot()?.status==='idle');
  check('reset clears result and stage effects',(await floor.evaluate(()=>moonfallFloor.world())).winner===null);
  await page.locator('#configure').click();await page.locator('#start').click();await wait(()=>moonfallSandbox.snapshot().status==='running');
  await wait(()=>moonfallSandbox.snapshot().robots.every(r=>r.s_cm>1));
  check('second match starts with new match id',(await state()).match_id!==match);
  await page.locator('#stop').click();await wait(()=>moonfallSandbox.snapshot().status==='stopped');
  check('stop command parks both robots',(await state()).robots.every(r=>r.stopped_confirmed));
  await page.locator('#reset').click();await wait(()=>moonfallSandbox.snapshot().status==='idle');
  // Leave user-ready live windows at a useful desktop size; normal random outcome and real time.
  await page.locator('#aftershock').selectOption('random');await page.locator('#speed').selectOption('1');
  await page.setViewportSize({width:1920,height:1080});await floor.setViewportSize({width:1920,height:1080});
  await page.locator('[data-view="overview"]').click();await page.waitForTimeout(3800);
  await page.screenshot({path:out+'/panorama.png'});await floor.locator('#floor-map').screenshot({path:out+'/floor.png'});
  check('no JavaScript errors',!errors.length,errors);check('no failed resources',!requests.length,requests);
  return {checks,errors,requests,performance,floor4k,finished:done,timeline,realHardwareConnected:false};
}
